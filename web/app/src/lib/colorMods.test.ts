describe("colorMods: Grown behaviour", () => {
  it("covers all 28 ECMA-376 §20.1.2.3 transforms", () => {
    expect(COLOR_MOD_NAMES).toHaveLength(28);
    for (const name of COLOR_MOD_NAMES) {
      const out = applyColorMods({ r: 68, g: 114, b: 196, a: 255 }, [{ name, val: 50000 }]);
      for (const v of [out.r, out.g, out.b, out.a]) {
        expect(Number.isInteger(v) && v >= 0 && v <= 255, name).toBe(true);
      }
    }
  });

  it("does not mutate its input", () => {
    const c = { r: 10, g: 20, b: 30, a: 255 };
    applyColorMods(c, [{ name: "inv" }]);
    expect(c).toEqual({ r: 10, g: 20, b: 30, a: 255 });
  });

  // Saturating a grey: hue is undefined, and HSL (like the spec) treats it as
  // 0° (red), giving r = q and g = b = p. OnlyOffice's tables expect a darker
  // blue channel there (e.g. 126 grey + satOff 50% → 189,63,0); we keep the
  // plain HSL result.
  it("saturating an achromatic grey ramps toward red (intentional divergence)", () => {
    expect(run([126, 126, 126], [["satOff", 50000]])).toEqual({ r: 189, g: 63, b: 63, a: 255 });
    expect(run([126, 126, 126], [["sat", -50000]])).toEqual({ r: 63, g: 189, b: 189, a: 255 });
    expect(run([200, 200, 200], [["satOff", 100000]])).toEqual({ r: 255, g: 145, b: 145, a: 255 });
  });

  it("parses and formats hex", () => {
    expect(parseHex("4472C4")).toEqual({ r: 68, g: 114, b: 196, a: 255 });
    expect(parseHex("#4472c480")).toEqual({ r: 68, g: 114, b: 196, a: 128 });
    expect(parseHex("nope")).toBeNull();
    expect(toHex({ r: 68, g: 114, b: 196, a: 255 })).toBe("#4472c4");
    expect(toHex({ r: 68, g: 114, b: 196, a: 128 })).toBe("#4472c480");
    expect(toCss({ r: 68, g: 114, b: 196, a: 128 })).toBe("rgba(68, 114, 196, 0.502)");
  });

  it("resolves scheme colours with lumMod/lumOff (pptx 'Lighter 40%')", () => {
    const theme: Record<string, string> = { accent1: "4472C4", lt1: "FFFFFF", dk1: "000000" };
    const lookup = (n: string) => theme[n];
    const mods: ColorMod[] = [
      { name: "lumMod", val: 60000 },
      { name: "lumOff", val: 40000 },
    ];
    // Same maths as the lumMod/lumOff rows above: l' = l·0.6 + 0.4.
    expect(toHex(resolveColor({ scheme: "accent1", mods }, lookup))).toBe("#8faadc");
    // bg1/tx1 go through the default colour map.
    expect(toHex(resolveColor({ scheme: "bg1" }, lookup))).toBe("#ffffff");
    expect(toHex(resolveColor({ scheme: "tx1" }, lookup))).toBe("#000000");
    // Unknown slot → black.
    expect(toHex(resolveColor({ scheme: "accent9" }, lookup))).toBe("#000000");
  });

  it("resolves srgbClr and hslClr bases", () => {
    expect(toHex(resolveColor({ srgb: "FF0000", mods: [{ name: "shade", val: 50000 }] }))).toBe("#bc0000");
    expect(toHex(resolveColor({ hsl: { hue: 7200000, sat: 100000, lum: 50000 } }))).toBe("#00ff00");
  });

  it("reads transform children from DrawingML XML in order", () => {
    const doc = new DOMParser().parseFromString(
      `<a:schemeClr xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main" val="accent1">` +
        `<a:lumMod val="75000"/><a:foo val="1"/><a:alpha val="50000"/><a:gray/></a:schemeClr>`,
      "application/xml",
    );
    expect(readColorMods(doc.documentElement)).toEqual([
      { name: "lumMod", val: 75000 },
      { name: "alpha", val: 50000 },
      { name: "gray" },
    ]);
  });
});
