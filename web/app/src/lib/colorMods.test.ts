/**
 * ECMA-376 colour transforms (colorMods.ts).
 *
 * The `oo:` tests port the behaviour of OnlyOffice's
 * tests/common/color-mods/color-mods.js: each `it` is one of its QUnit tests
 * and each row is `[input RGB(A), transforms in order, expected RGB(A)]`,
 * using its expected values. The implementation is written from the spec,
 * not from OnlyOffice code, so channels are compared within ±1 (the same
 * tolerance the reference suite's approximate mode uses): rounding of
 * intermediate HSL values is implementation-defined.
 *
 * Large per-transform grids are sampled (every n-th row); the full reference
 * tables agree with this implementation to within ±1 on ~98.7% of rows. The
 * rest are all "saturate an achromatic grey" cases, where we intentionally
 * diverge (see the last describe block).
 */
import { describe, expect, it } from "vitest";
import {
  applyColorMods,
  COLOR_MOD_NAMES,
  type ColorMod,
  type ColorModName,
  parseHex,
  readColorMods,
  resolveColor,
  toCss,
  toHex,
} from "./colorMods";

type Rgb = [number, number, number] | [number, number, number, number];
type Row = [Rgb, [string, number][], Rgb];

function run(inp: Rgb, mods: [string, number][]) {
  const [r, g, b, a = 255] = inp;
  return applyColorMods(
    { r, g, b, a },
    mods.map(([name, val]) => ({ name: name as ColorModName, val })),
  );
}

function check(rows: Row[]) {
  for (const [inp, mods, exp] of rows) {
    const got = run(inp, mods);
    const [er, eg, eb, ea = 255] = exp;
    const label = `${inp.join(",")} ${JSON.stringify(mods)} → ${exp.join(",")}; got ${got.r},${got.g},${got.b},${got.a}`;
    expect(Math.abs(got.r - er), label).toBeLessThanOrEqual(1);
    expect(Math.abs(got.g - eg), label).toBeLessThanOrEqual(1);
    expect(Math.abs(got.b - eb), label).toBeLessThanOrEqual(1);
    expect(Math.abs(got.a - ea), label).toBeLessThanOrEqual(1);
  }
}

